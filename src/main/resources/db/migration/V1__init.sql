-- Initial schema: the tables Hibernate generated until now, with named constraints and
-- indexes on the foreign keys the queries filter by. Hibernate only validates it
-- (spring.jpa.hibernate.ddl-auto=validate).

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(254) NOT NULL,
    password             VARCHAR(255) NOT NULL,
    first_name           VARCHAR(100),
    last_name            VARCHAR(100),
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    reset_password_token VARCHAR(255),
    birthdate            DATE,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE vehicles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id          BIGINT       NOT NULL,
    type              VARCHAR(50)  NOT NULL,
    brand             VARCHAR(50)  NOT NULL,
    model             VARCHAR(50)  NOT NULL,
    license_plate     VARCHAR(10)  NOT NULL,
    vin               VARCHAR(17)  NOT NULL,
    mileage           BIGINT       NOT NULL,
    registration_year INTEGER      NOT NULL,
    fuel              VARCHAR(20)  NOT NULL,
    avg_km_per_year   BIGINT,
    deleted_at        TIMESTAMP(6),
    CONSTRAINT fk_vehicles_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT ck_vehicles_fuel CHECK (fuel IN ('BENZINA', 'DIESEL', 'ELETTRICO', 'GPL', 'METANO', 'IBRIDO')),
    CONSTRAINT ck_vehicles_mileage CHECK (mileage >= 0)
);
CREATE INDEX idx_vehicles_owner ON vehicles (owner_id);

CREATE TABLE maintenance_tasks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id         BIGINT        NOT NULL,
    title              VARCHAR(255)  NOT NULL,
    description        VARCHAR(255)  NOT NULL,
    scheduled_date     TIMESTAMP(6)  NOT NULL,
    scheduled_mileage  BIGINT        NOT NULL,
    status             VARCHAR(20)   NOT NULL,
    priority           VARCHAR(20)   NOT NULL,
    estimated_cost     NUMERIC(10, 2),
    actual_cost        NUMERIC(10, 2),
    completion_date    TIMESTAMP(6),
    completion_mileage BIGINT,
    notes              VARCHAR(255),
    CONSTRAINT fk_maintenance_tasks_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id),
    CONSTRAINT ck_maintenance_tasks_status CHECK (status IN ('PENDING', 'OVERDUE', 'COMPLETED')),
    CONSTRAINT ck_maintenance_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT'))
);
CREATE INDEX idx_maintenance_tasks_vehicle ON maintenance_tasks (vehicle_id);
-- The nightly job and the reminders read tasks by status
CREATE INDEX idx_maintenance_tasks_status ON maintenance_tasks (status, scheduled_date);

CREATE TABLE reminders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    type              VARCHAR(30)  NOT NULL,
    title             VARCHAR(255) NOT NULL,
    message           VARCHAR(255) NOT NULL,
    notification_date TIMESTAMP(6) NOT NULL,
    notified          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_reminders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_reminders_type CHECK (type IN ('PENDING_TASKS', 'OVERDUE_TASKS', 'MAINTENANCE_SUMMARY'))
);
CREATE INDEX idx_reminders_user ON reminders (user_id);

CREATE TABLE reminder_tasks (
    reminder_id BIGINT NOT NULL,
    task_id     BIGINT NOT NULL,
    PRIMARY KEY (reminder_id, task_id),
    CONSTRAINT fk_reminder_tasks_reminder FOREIGN KEY (reminder_id) REFERENCES reminders (id),
    CONSTRAINT fk_reminder_tasks_task FOREIGN KEY (task_id) REFERENCES maintenance_tasks (id)
);
CREATE INDEX idx_reminder_tasks_task ON reminder_tasks (task_id);

CREATE TABLE documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id   BIGINT       NOT NULL,
    user_id      BIGINT       NOT NULL,
    name         VARCHAR(255) NOT NULL,
    type         VARCHAR(40)  NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    content      BYTEA        NOT NULL,
    upload_date  TIMESTAMP(6),
    CONSTRAINT fk_documents_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id),
    CONSTRAINT fk_documents_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_documents_type CHECK (type IN ('LIBRETTO_DI_CIRCOLAZIONE', 'ASSICURAZIONE', 'BOLLO',
                                                 'FATTURA_MANUTENZIONE', 'LIBRETTO_MANUTENZIONE_PREGRESSA'))
);
CREATE INDEX idx_documents_vehicle ON documents (vehicle_id);

-- Spring Modulith event publication registry (JpaEventPublication). serialized_event is
-- wider than Hibernate's default 255: a JSON event can be longer.
CREATE TABLE event_publication (
    id                     UUID          NOT NULL PRIMARY KEY,
    listener_id            VARCHAR(512)  NOT NULL,
    event_type             VARCHAR(512)  NOT NULL,
    serialized_event       VARCHAR(4000) NOT NULL,
    publication_date       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completion_date        TIMESTAMP(6) WITH TIME ZONE,
    status                 VARCHAR(20),
    completion_attempts    INTEGER       NOT NULL DEFAULT 0,
    last_resubmission_date TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_event_publication_completion_date ON event_publication (completion_date);
